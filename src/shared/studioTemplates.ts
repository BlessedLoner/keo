/**
 * Keo Studio's template gallery: ready-made titles, intros, lower thirds, promo graphics, social
 * cards, cinematic looks and end cards. Each is a few ordinary edits (motion graphics, text, an
 * adjustment layer) placed at the playhead, so every part stays editable afterwards — nothing is
 * a flattened video. Names and colours come from the brand kit when there is one.
 */
